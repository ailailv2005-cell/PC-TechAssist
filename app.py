import streamlit as st

st.set_page_config(
    page_title="PC TechAssist",
    page_icon="💻",
    layout="wide"
)

# شريط جانبي بمعلومات سريعة
with st.sidebar:
    st.image("https://img.icons8.com/color/96/motherboard.png", width=80)
    st.title("PC TechAssist")
    st.write("مساعدك الذكي لتشخيص وصيانة عتاد الحواسيب للمبتدئين.")
    st.markdown("---")
    st.info("💡 **نصيحة تقنية:** افصل التيار الكهربائي دائماً قبل صيانة أي قطعة داخل الحاسوب.")

# العنوان الرئيسي مع تصميم أنيق
st.title("💻 PC TechAssist - منصة تشخيص أعطال الحواسيب")
st.markdown("مرحباً بك في أداة التشخيص التفاعلية. حدد نوع المشكلة والقطعة المستهدفة لنقدم لك الحلول الفورية.")
st.markdown("---")

# تقسيم الشاشة إلى عمودين لتجربة مستخدم أفضل
col1, col2 = st.columns(2)

with col1:
    issue = st.selectbox(
        "اختر نوع المشكلة الأساسية:",
        ["مشكلة إقلاع الجهاز (Boot)", "ارتفاع حرارة المعالج أو النظام", "مشكلة في الشاشة أو كرت الشاشة", "مشكلة في الاتصال بالشبكة"]
    )

with col2:
    hardware_part = st.selectbox(
        "حدد القطعة المستهدفة:",
        ["الذاكرة العشوائية (RAM)", "المعالج (CPU)", "لوحة الأم (Motherboard)", "كرت الشاشة (GPU)", "مزود الطاقة (Power Supply)"]
    )

# حقل كتابة التفاصيل بمساحة واسعة
details = st.text_area(
    "اكتب تفاصيل المشكلة أو الأعراض الملاحظة:",
    placeholder="مثلاً: الجهاز يصدر أصوات صفير عند الإقلاع ولا يقلع النظام..."
)

# زر التشخيص التفاعلي
if st.button("🔍 تحليل الأعراض وتقديم الحل"):
    if details.strip() != "":
        st.success("تم تحليل بيانات القطعة والمشكلة بنجاح!")
        st.markdown("### 🛠️ تقرير التشخيص والتوجيهات المقترحة:")
        
        # عرض الحلول بناءً على القطعة أو المشكلة المحددة
        if "RAM" in hardware_part or "إقلاع" in issue:
            st.info("💡 **إجراءات الصيانة المقترحة للـ RAM والإقلاع:**\n1. أخرج ذواكر الرام ونظف نقاط التوصيل الذهبية بقطعة قماش جافة أو ممحاة.\n2. جرب تركيب الرام في شقوق (Slots) مختلفة.\n3. أعد ضبط إعدادات الـ BIOS عبر إزالة بطارية CMOS لعدة دقائق.")
        elif "حرارة" in issue or "CPU" in hardware_part:
            st.warning("🔥 **إجراءات الصيانة المقترحة للحرارة والمعالج:**\n1. تحقق من سرعة دوران مروحة المعالج وتأكد من عملها.\n2. قم بتنظيف الأتربة المتراكمة داخل مبرد الهواء.\n3. أزل مبرد المعالج ونظف المعجون القديم وضع طبقة معجون حراري جديدة.")
        elif "كرت الشاشة" in hardware_part or "الشاشة" in issue:
            st.markdown("🖥️ **إجراءات الصيانة المقترحة لكرت الشاشة:**\n1. تأكد من إحكام توصيل كابل الشاشة بكرت الشاشة مباشرة وليس بلوحة الأم.\n2. أعد تثبيت كرت الشاشة في منفذ الـ PCIe وتأكد من كابلات الطاقة القادمة من مزود الطاقة.")
        else:
            st.markdown("🌐 **إجراءات الصيانة العامة للشبكة:**\n1. أعد تشغيل موجه الأوامر (الراوتر).\n2. تحقق من تعريفات كرت الشبكة عبر مدير الجهاز (Device Manager).")
    else:
        st.error("الرجاء كتابة تفاصيل المشكلة في الخانة المخصصة قبل البدء بالتشخيص.")
        
