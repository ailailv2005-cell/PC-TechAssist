    st.header("⚡ إرشادات السلامة والتفريغ الكهروستاتيكي (ESD)")
    st.write("قواعد أساسية صارمة يجب اتباعها قبل البدء بأي عملية صيانة لحماية المكونات الحساسة:")
    
    st.warning("⚠️ **تنبيه هام جداً:** الشحنات الساتيكية في جسم الإنسان قادرة على إتلاف الدوائر الدقيقة فوراً!")
    
    st.markdown("""
    1. **التفريغ الأرضي:** المس جسماً معدنياً غير مفصول (مثل الهيكل الخارجي للكيس) لتفريغ الشحنات الساكنة.
    2. **فصل الطاقة الكلية:** افصل كابل الطاقة من الحائط تماماً قبل فتح وغلق أجزاء اللوحة الأم.
    3. **استخدام أدوات معزولة:** احرص على استخدام مفكات معزولة والعمل على طاولات خشبية أو غير موصلة للكهرباء.
    """)
    
