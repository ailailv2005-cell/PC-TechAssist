import streamlit as st

st.set_page_config(
    page_title="PC TechAssist",
    page_icon="💻",
    layout="centered"
)

st.title("💻 PC TechAssist")
st.subheader("مساعد تشخيص أعطال الحاسوب - نسخة الهاكاثون")
st.write("مرحباً بك! هذا التطبيق مصمم لمساعدة المبتدئين في صيانة وتشخيص قطع الحواسيب.")
st.markdown("---")

# اختيار نوع المشكلة
issue = st.selectbox(
    "اختر نوع المشكلة الأساسية:",
    ["مشكلة إقلاع الجهاز (Boot)", "ارتفاع حرارة المعالج أو النظام", "مشكلة في الاتصال بالشبكة"]
)

# حقل كتابة التفاصيل
details = st.text_area(
    "اكتب تفاصيل المشكلة أو أعراضها هنا:",
    placeholder="مثلاً: الجهاز يعمل ولكن لا تظهر صورة على الشاشة..."
)

# زر التشخيص التفاعلي
if st.button("🔍 ابدأ التشخيص"):
    if details.strip() != "":
        st.success("تم استلام طلب التشخيص وتحليل البيانات بنجاح!")
        st.markdown("### 🛠️ النتائج والخطوات المقترحة:")
        
        if "إقلاع" in issue:
            st.info("💡 **التوجيه المقترح:** تحقق من تركيب ذواكر الرام (RAM) ونظف نقاط التوصيل الخاصة بها، أو أعد ضبط بطارية CMOS.")
        elif "حرارة" in issue:
            st.warning("🔥 **التوجيه المقترح:** تحقق من نظافة المراوح، وتأكد من حالة المعجون الحراري فوق المعالج.")
        else:
            st.markdown("🌐 **التوجيه المقترح:** قم بإعادة تشغيل موجه الأوارم (الراوتر) وتأكد من تعريفات كرت الشبكة.")
    else:
        st.error("الرجاء كتابة تفاصيل المشكلة في الخانة المخصصة أولاً.")
      
