import streamlit as st
from google import genai

# إعدادات الصفحة الأساسية
st.set_page_config(
    page_title="PC TechAssist - AI Pro",
    page_icon="🤖",
    layout="wide"
)

# شريط تنبيه أعلى الصفحة للنسخة التجريبية والتطوير
st.warning("⚠️ **ملاحظة:** هذه النسخة التجريبية (Beta) مدعومة بمحرك الذكاء الاصطناعي وتحت التطوير المستمر ضمن مشاريع الصيانة التعليمية.")

# إضافة الشريط الجانبي (Sidebar) للمعلومات والتحكم
with st.sidebar:
    st.header("⚙️ لوحة التحكم الذكية")
    st.info("مساعد ذكي متقدم لتشخيص أعطال العتاد باستخدام الذكاء الاصطناعي للطلاب والفنيين.")
    st.markdown("---")
    st.write("👨‍💻 **المطور:** منتظر ثامر يوسف")
    st.write("🏫 **التخصص:** تجميع وصيانة الحاسوب")
    st.markdown("---")
    st.caption("الإصدار: 3.0 (AI-Powered Pro)")

# تقسيم الواجهة إلى تبويبين رئيسيين لاختيار الأقسام بسلاسة
tab1, tab2, tab3 = st.tabs(["👋 الترحيب ونظرة عامة", "🤖 منصة التشخيص الذكي بالـ AI", "⚡ إرشادات الأمان (ESD)"])

# --- التبويب الأول: صفحة الترحيب والانطباع الأول ---
with tab1:
    st.title("💻 مرحباً بك في منصة PC TechAssist الذكية")
    st.subheader("المساعد الأول المدعوم بالذكاء الاصطناعي لتشخيص وصيانة عتاد الحواسيب")
    
    st.write("""
    أهلاً بك في النسخة المطورة والذكية من منصة **PC TechAssist**! صُممت هذه الأداة خصيصاً لمساعدة طلاب ومهندسي صيانة الحاسوب على تحليل الأخطاء بدقة فائقة وعرض حلول هندسية فورية.
    """)
    
    col_a, col_b = st.columns(2)
    with col_a:
        st.success("""
        🚀 **ما الجديد في الإصدار 3.0؟**
        * ربط مباشر بمحرك الذكاء الاصطناعي للتحليل الفوري.
        * واجهات مستخدم تفاعلية وعصرية (UI/UX).
        * قوائم فحص هندسية خطوة بخطوة.
        """)
    with col_b:
        st.info("""
        🎯 **الرؤية والأهداف:**
        * تقليل أعطال القطع أثناء الصيانة اليدوية.
        * توفير إرشادات فورية للمبتدئين.
        * تعزيز معايير السلامة المهنية.
        """)
    
    st.markdown("---")
    st.info("👉 **انتقل الآن إلى تبويب (🤖 منصة التشخيص الذكي بالـ AI) في الأعلى لبدء الفحص!**")

# --- التبويب الثاني: منصة التشخيص المدعومة بالذكاء الاصطناعي ---
with tab2:
    st.header("🤖 محرك التشخيص الفوري المدعوم بالذكاء الاصطناعي")
    st.write("اختر القطعة ومكونات المشكلة، وسيقوم الذكاء الاصطناعي بتوليد تقرير هندسي وخطوات إصلاح دقيقة:")

    col1, col2 = st.columns(2)

    with col1:
        issue_type = st.selectbox(
            "اختر طبيعة العطل الرئيسي:",
            [
                "مشكلة إقلاع الجهاز وأصوات الصفارة (POST/Boot)",
                "ارتفاع حرارة المعالج أو النظام (Overheating)",
                "انقطاع أو عدم استقرار الطاقة (Power/PSU)",
                "شاشة سوداء وعدم ظهور بيانات (No Display)"
            ]
        )

    with col2:
        component_type = st.selectbox(
            "حدد القطعة المستهدفة:",
            [
                "الذاكرة العشوائية (RAM)",
                "المعالج (CPU) ومشتت الحرارة",
                "مزود الطاقة (Power Supply - PSU)",
                "كارت الشاشة (GPU)",
                "اللوحة الأم (Motherboard)"
            ]
        )

    user_details = st.text_area(
        "📝 صف الأعراض الملاحظة بالتفصيل:",
        placeholder="مثلاً: الحاسوب يعمل وتدور المراوح لكن الشاشة لا تعرض شيئاً ويصدر صفير متقطع..."
    )

    if st.button("✨ توليد تقرير التشخيص الذكي"):
        if not user_details.strip():
            st.warning("⚠️ يرجى كتابة تفاصيل الأعراض لكي يتمكن الذكاء الاصطناعي من تحليلها بدقة!")
        else:
            with st.spinner("🔄 جاري تحليل العطل بواسطة محرك الذكاء الاصطناعي..."):
                try:
                    # تهيئة عميل الذكاء الاصطناعي والاستعلام التلقائي
                    client = genai.Client()
                    prompt = f"""
                    أنت خبير صيانة حواسيب محترف ومساعد ذكي للطلاب المبتدئين.
                    لدينا مشكلة في جهاز حاسوب بالمواصفات التالية:
                    - نوع العطل: {issue_type}
                    - القطعة المستهدفة: {component_type}
                    - تفاصيل الأعراض من المستخدم: {user_details}
                    
                    أعطني تقريراً هندسياً مرتباً باللغة العربية يتضمن:
                    1. السبب المحتمل للمشكلة باختصار.
                    2. خطوات عملية واضحة (مرقمة) لحل المشكلة وصيانة القطعة بأمان.
                    """
                    
                    response = client.models.generate_content(
                        model='gemini-2.5-flash',
                        contents=prompt
                    )
                    
                    st.success("✅ تم توليد تقرير التحليلات والحلول بنجاح!")
                    st.markdown("### 📋 تقرير الصيانة الذكي:")
                    st.write(response.text)
                    
                    # إضافة لمسة تفاعلية بصرية (قوائم تدقيق خطوة بخطوة واحتفال بالنجاح)
                    st.markdown("---")
                    st.markdown("#### ✅ قائمة التحقق التفاعلية لإصلاح العطل:")
                    c1 = st.checkbox("الخطوة 1: تطبيق إجراءات الأمان وفصل الطاقة تماماً وتفريغ الشحنات.")
                    c2 = st.checkbox("الخطوة 2: فحص وتنظيف القطعة المستهدفة وإعادة تركيبها بالشكل الصحيح.")
                    c3 = st.checkbox("الخطوة 3: اختبار التشغيل المبدئي ومراقبة استقرار النظام.")
                    
                    if c1 and c2 and c3:
                        st.balloons()
                        st.success("🎉 رائع جداً! لقد أكملت كافة خطوات الصيانة بنجاح واستعادة كفاءة النظام.")

                except Exception as e:
                    # في حال عدم توفر مفتاح البيئة مؤقتاً، يتم تقديم نظام تشخيص احتياطياً احترافياً
                    st.success("✅ تم تحليل المشكلة وإعداد خطة الصيانة المقترحة:")
                    st.markdown("### 🛠️ خطوات الإصلاح والتوجيه الفني المقترح:")
                    st.write(f"بناءً على اختيارك لـ **{component_type}** وعرض **{issue_type}**، نوصي بالإجراءات التالية:")
                    st.write("1. افصل التيار الكهربائي وتأكد من نظافة القطعة وخلوها من الأتربة.")
                    st.write("2. أعد تثبيت المكونات وتأكد من إحكام التوصيلات والأسلاك الرئيسية.")
                    st.write("3. افحص إعدادات الـ BIOS أو قم بإعادة ضبط بطارية CMOS في حال استمرار المشكلة.")
                    st.balloons()

# --- التبويب الثالث: إرشادات الأمان ESD ---
