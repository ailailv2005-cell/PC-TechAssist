app.py
import streamlit as st

# إعداد الصفحة وتصميم الواجهة
st.set_page_config(
    page_title="PC TechAssist - AI Hardware Diagnostic",
    page_icon="💻",
    layout="wide"
)

# تخصيص العنوان والترحيب
st.title("💻 PC TechAssist")
st.subheader("مساعدك الذكي لتشخيص وصيانة أعطال الحواسيب للمبتدئين والفنيين")
st.markdown("---")

# الشريط الجانبي لمعلومات النظام أو المطور
with st.sidebar:
    st.header("حول النظام")
    st.info("هذا التطبيق مصمم لمساعدة طلاب ومبتدئي صيانة الحواسيب في تحليل الأعطال الشائعة وتقديم خطوات إصلاح دقيقة ومنهجية.")
    st.markdown("---")
    st.write("🚀 **إصدار المشروع:** 1.0.0 (نسخة الهاكاثون)")

# واجهة المدخلات الرئيسية
col1, col2 = st.columns(2)

with col1:
    st.write("### 🛠️ تحديد نوع المشكلة:")
    issue_category = st.selectbox(
        "اختر تصنيف العطل الأساسي:",
        [
            "مشكلة في الإقلاع (Boot / No Display)",
            "ارتفاع حرارة المعالج أو النظام (Overheating)",
            "مشكلة في الاتصال بالشبكة / الإنترنت",
            "بطء شديد في النظام أو تهنيج (Performance Lag)",
            "مشكلة في الشاشة الزرقاء (BSOD)",
            "أعطال أخرى"
        ]
    )

with col2:
    st.write("### 🎛️ مكونات النظام المستهدفة:")
    hardware_part = st.multiselect(
        "حدد القطع المشكوك فيها:",
        ["اللوحة الأم (Motherboard)", "الذاكرة العشوائية (RAM)", "قرص التخزين (SSD/HDD)", "مزود الطاقة (Power Supply)", "المعالج (CPU)", "كرت الشاشة (GPU)"]
    )

# تفاصيل المشكلة الدقيقة
st.markdown("---")
user_details = st.text_area(
    "📝 اكتب تفاصيل المشكلة أو أعراضها بدقة (مثلاً: الجهاز يشتغل لكن لا تظهر صورة على الشاشة وتصدر أصوات صفير):",
    placeholder="اكتب هنا الأعراض بالتفصيل لكي يساعدك النظام في التشخيص..."
)

# زر التشخيص وتحليل المشكلة
if st.button("🔍 بدء التشخيص الذكي", type="primary"):
    if user_details.strip() != "":
        st.success("تم استلام بيانات الفحص وتحليل مدخلات النظام بنجاح!")
        
        st.markdown("---")
        st.markdown("## 📊 تقرير التشخيص وخطوات الإصلاح المقترحة:")
        
        # تحليل استناداً إلى التصنيف
        if "الإقلاع" in issue_category:
            st.warning("⚠️ **تشخيص مبدئي:** المشكلة تتعلق بعدم اكتمال دورة الإقلاع (POST).")
            st.markdown("""
            **خطوات الإصلاح الموصى بها للمبتدئين:**
            1. **فحص الذاكرة (RAM):** قم بإيقاف تشغيل الجهاز، فك قطع الرام، نظف نقاط التوصيل برفق، وأعد تركيبها بوضع محكم.
            2. **إعادة ضبط BIOS:** قم بإزالة بطارية CMOS لمدة 5 دقائق لإعادة إعدادات اللوحة الأم للوضع الافتراضي.
            3. **التوصيلات:** تأكد من إحكام توصيل كابلات الطاقة القادمة من مزود الطاقة (PSU) إلى اللوحة الأم.
            """)
        elif "حرارة" in issue_category:
            st.error("🔥 **تشخيص مبدئي:** خطر ارتفاع درجة الحرارة قد يؤدي إلى إيقاف تشغيل حماية النظام (Thermal Throttling).")
            st.markdown("""
            **خطوات الإصلاح الموصى بها:**
            1. **تنظيف المراوح:** إزالة الأتربة المتراكمة على المشتت الحراري ومروحة المعالج.
            2. **المعجون الحراري:** فحص المعجون القديم على سطح المعالج واستبداله بطبقة جديدة عالية الجودة (Thermal Paste).
            3. **تدفق الهواء:** التأكد من حركة الهواء داخل صندوق الكيسة (Chassis).
            """)
        elif "الشبكة" in issue_category:
            st.info("🌐 **تشخيص مبدئي:** انقطاع أو عدم استقرار اتصال الشبكة.")
            st.markdown("""
            **خطوات الإصلاح الموصى بها:**
            1. **إعادة تشغيل الراوتر:** فصل الطاقة عن الراوتر وإعادة تشغيله بعد 30 ثانية.
            2. **تعريفات كارت الشبكة:** التأكد من تثبيت أحدث تعريف (Driver) لكرت الشبكة من إدارة الأجهزة (Device Manager).
            3. **أوامر الشبكة:** تشغيل موجه الأوامر (CMD) كمسؤول وكتابة `ipconfig /flushdns`.
            """)
        else:
            st.info("💡 **تحليل عام للحالة:**")
            st.markdown("""
            **التوصيات العامة للفحص:**
            1. فحص ملفات نظام التشغيل عبر أمر `sfc /scannow` في موجه الأوامر.
            2. مراقبة استهلاك المعالج والذاكرة من خلال إدارة المهام (Task Manager).
            3. التأكد من خلو النظام من البرمجيات الخبيثة.
            """)
            
        # عرض القطع المحددة إن وجدت
        if hardware_part:
            st.markdown(f"📌 **القطع التي تم التركيز عليها في الفحص:** `{', '.join(hardware_part)}`")
            
    else:
        st.error("الرجاء كتابة وصف تفصيلي للمشكلة في الخانة المخصصة قبل النقر على زر التشخيص.")

st.markdown("---")
st.caption("PC TechAssist Project | تم تطويره لدعم مشاريع صيانة الحواسيب وتدريب الطلاب 🚀")
          
