            problem_lower = user_problem.lower()
            
            if "رام" in problem_lower or "ram" in problem_lower or "ذاكرة" in problem_lower:
                st.write("1. **إخراج الشرائح:** افصل الكهرباء تماماً عن الجهاز واخرج شرائح الذاكرة (RAM) بحذر.")
